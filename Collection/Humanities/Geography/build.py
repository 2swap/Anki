"""Regenerate the Geography deck's TSVs from the geog_*.js data files.

This is the manifest "build" step for anki_sync.py. It does not touch AnkiConnect.
Run by hand from this directory if you want:  python build.py

Writes Feature.tsv (every note, plus the media-saver note) and manifest.json's
"media" map. All notes go in this folder's one Anki deck, tagged with their
data folder (Geography::<Folder>) rather than split into subdecks.

Each feature becomes one note whose "Name" field is

    <feature label>::<js suffix>

matching what geog.js expects (it splits Name on "::" to get the feature name
and the geog_<suffix>.js data file to load). The js suffix is the part of the
filename between "geog_" and ".js"; for most folders it equals the folder name,
but some differ (British Isles/geog_UK.js, Spain/geog_Espana.js, ...). The
"Media" field is empty; only the one suspended media-saver note fills it.
"""

import csv
import glob
import json
import os
import re
import unicodedata

MODEL = "Feature"

# Everything goes into one Anki deck (named by this folder's path under Collection/); each note is tagged with its
# data folder in Data/ (Geography::Central_Asia, ...) instead of a subdeck per folder.
TAG_PREFIX = "Geography::"
# Data folders kept in the repo but left out of Anki for now (no notes, no media).
EXCLUDED_FOLDERS = {"Indonesia_Kabupaten"}
# Folders whose region (polygon) features get no notes for now; their cities
# still do, and the regions are still drawn as context on the map.
NO_REGION_NOTES = {"Gulf States"}  # the 7 UAE emirates
MEDIA_SAVER_NAME = "_media_saver"
SHARED_MEDIA = ["geog.js", "_noto_sans_arabic.woff2"]

# properties objects in the data are flat (no nested braces), so this reliably
# yields exactly one match per feature regardless of how the geometry wraps.
PROPS_RE = re.compile(r'"properties"\s*:\s*\{([^{}]*)\}')
NAME_RE = re.compile(r'"name"\s*:\s*"([^"]*)"')
NAME_EN_RE = re.compile(r'"name_en"\s*:\s*"([^"]*)"')


def check_js(js_path):
    """Fail the build if a data file wouldn't run in the card.

    A syntax error (e.g. a missing comma between two features) makes the whole
    file fail in the browser, so every card of that deck silently shows an
    empty map (seen 2026-09-30 in 7 files). The files are
    `countryjson.features.push(...[ <features> ]);` with // comment lines, so
    the feature list is checked as JSON (a trailing comma is allowed, as in JS).
    """
    text = open(js_path, encoding="utf-8").read()
    body = "\n".join(l for l in text.split("\n") if not l.strip().startswith("//"))
    m = re.search(r"countryjson\.features\.push\(\s*\.\.\.\s*\[(.*)\]\s*\)\s*;?\s*$", body, re.S)
    if not m:
        raise SystemExit(f"{js_path}: expected countryjson.features.push(...[ ... ]);")
    try:
        feats = json.loads("[" + re.sub(r",\s*$", "", m.group(1)) + "]")
    except json.JSONDecodeError as e:
        raise SystemExit(f"{js_path}: broken feature list ({e}); the card would show an empty map")
    if len(feats) != len(PROPS_RE.findall(body)):
        raise SystemExit(f"{js_path}: {len(feats)} features parse but {len(PROPS_RE.findall(body))} have properties")
    return feats


REGION_MARK = " [region]"
# Regions whose English label differs only slightly from a same-named city's
# (Melaka the state vs. the city labelled Malacca), marked by hand so the note
# says which one it means. Other such pairs (São Paulo / Sao Paulo, ...) are
# left unmarked, matching the live collection.
ALSO_REGION_MARKED = {"Melaka", "Neuquén", "Potosí"}

# Pronunciations: Data/<folder>/geogaudio_<file-safe properties.name>.mp3 in
# the repo, stored in Anki as geogaudio_<js suffix>_<file-safe name>.mp3 (one
# flat media folder, so the suffix keeps same-named places in different files
# apart). Anki lowercases stored names; geog.js builds the same name.
UNSAFE_RE = re.compile(r'[\\/:*?"<>|]')


def file_safe(name):
    return UNSAFE_RE.sub("_", name)


# Pronunciations generated by audio_scrape/tts_fill.py rather than recorded by a
# person: their AUDIO_CREDITS.tsv row has this found_via, and their notes get
# AI_VOICE_TAG on top of the folder tag.
TTS_SOURCE = "elevenlabs_tts"
AI_VOICE_TAG = TAG_PREFIX + "AI_Voice"


def tts_mp3s(geog_dir):
    path = os.path.join(geog_dir, "AUDIO_CREDITS.tsv")
    if not os.path.exists(path):
        return set()
    with open(path, encoding="utf-8", newline="") as fh:
        return {r["mp3"] for r in csv.DictReader(fh, delimiter="\t") if r["found_via"] == TTS_SOURCE}


def audio_media_name(suffix, name):
    return unicodedata.normalize("NFC", f"geogaudio_{suffix}_{file_safe(name)}.mp3".lower())


def feature_labels(feats):
    """(label, is_point, name) per feature; the label is name_en, else name.

    When a region and a city in the same file share a name (Salta the province
    and Salta the city, Moscow the federal subject and the city, ...), the
    region's label gets REGION_MARK, so both get a note. geog.js strips the mark
    and then matches only regions; an unmarked name prefers the city. Regions
    in ALSO_REGION_MARKED are marked too.
    """
    labels = [(f["properties"].get("name_en") or f["properties"].get("name") or "",
               f["geometry"]["type"] == "Point", f["properties"].get("name") or "") for f in feats]
    city_names = {l for l, is_point, _ in labels if is_point}
    return [(l + REGION_MARK if (not is_point and (l in city_names or l in ALSO_REGION_MARKED)) else l, is_point, n)
            for l, is_point, n in labels if l]


def bluemarble_media(geog_dir):
    """The Blue Marble basemap + tiles that build_tiles.py writes (git-ignored)."""
    bm = os.path.join(geog_dir, "bluemarble")
    tiles = sorted(glob.glob(os.path.join(bm, "tiles", "geog_bm_*.jpg")))
    if not os.path.exists(os.path.join(bm, "geog_bluemarble.jpg")) or not tiles:
        raise SystemExit("Blue Marble tiles missing: run  python Geography/build_tiles.py")
    media = {"geog_bluemarble.jpg": "bluemarble/geog_bluemarble.jpg"}
    for t in tiles:
        media[os.path.basename(t)] = os.path.relpath(t, geog_dir)
    return media


def write_tsv(path, rows):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, delimiter="\t", lineterminator="\n")
        writer.writerow(["Name", "Media", "Tags"])
        writer.writerows(rows)


def main():
    geog_dir = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(geog_dir, "Data")
    rows = []       # [name, media, tags]
    js_of = {}      # name -> its data file, relative to Geography/
    audio_of = {}   # name -> (Anki media name, mp3 relative to Geography/), when recorded
    seen = set()
    for folder in sorted(os.listdir(data_dir)):
        fdir = os.path.join(data_dir, folder)
        js_files = sorted(glob.glob(os.path.join(fdir, "geog_*.js")))
        if not os.path.isdir(fdir) or not js_files or folder in EXCLUDED_FOLDERS:
            continue
        tag = TAG_PREFIX + folder.replace(" ", "_")
        n = 0
        for js_path in js_files:
            feats = check_js(js_path)
            suffix = os.path.basename(js_path)[len("geog_"):-len(".js")]
            for label, is_point, pname in feature_labels(feats):
                if not is_point and folder in NO_REGION_NOTES:
                    continue
                if label.startswith("("):
                    print(f"  ! {folder}: skipping feature with unusable name {label!r}")
                    continue
                name = f"{label}::{suffix}"
                if name in seen:
                    print(f"  ! {folder}: duplicate feature {name!r}, keeping first only")
                    continue
                seen.add(name)
                rows.append([name, "", tag])
                js_of[name] = os.path.join("Data", folder, os.path.basename(js_path))
                mp3 = os.path.join("Data", folder, f"geogaudio_{file_safe(pname)}.mp3")
                if pname and os.path.exists(os.path.join(geog_dir, mp3)):
                    audio_of[name] = (audio_media_name(suffix, pname), mp3)
                n += 1
        print(f"  {folder}: {n} notes")
    tts = tts_mp3s(geog_dir)
    for r in rows:
        if r[0] in audio_of and audio_of[r[0]][1] in tts:
            r[2] += " " + AI_VOICE_TAG
    print(f"total: {len(rows)} notes, {len(audio_of)} with a pronunciation"
          f" ({sum(AI_VOICE_TAG in r[2] for r in rows)} AI voice)")

    media = {f: f"media/{f}" for f in SHARED_MEDIA}
    media.update(bluemarble_media(geog_dir))
    for js_rel in sorted(set(js_of.values())):
        # This AnkiConnect lowercases stored media names; geog.js asks for the lowercase name.
        media[os.path.basename(js_rel).lower()] = js_rel
    for r in rows:
        if r[0] in audio_of:
            media[audio_of[r[0]][0]] = audio_of[r[0]][1]
    # One suspended note whose Media field references every file the cards
    # load by script, so Check Media keeps them and AnkiWeb syncs them (see README.md).
    saver = [MEDIA_SAVER_NAME, "".join(f"[sound:{f}]" for f in media), "media_saver"]
    write_tsv(os.path.join(geog_dir, f"{MODEL}.tsv"), rows + [saver])
    print(f"  {MODEL}.tsv: {len(rows)} notes + media saver")

    manifest_path = os.path.join(geog_dir, "manifest.json")
    with open(manifest_path, encoding="utf-8") as fh:
        manifest = json.load(fh)
    manifest.pop("decks", None)
    manifest["media"] = media
    with open(manifest_path, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


if __name__ == "__main__":
    main()
